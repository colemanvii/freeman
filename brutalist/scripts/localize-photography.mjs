#!/usr/bin/env node
/* Localize photography
 * --------------------------------------------------------------
 * Downloads every freemangc.com CDN image referenced in /brutalist/data
 * into /brutalist/assets/photography/ and writes data/local-photography.js
 * so pages use the local copy first (CDN stays as fallback).
 *
 *   cd brutalist && node scripts/localize-photography.mjs
 *
 * Requires Node 18+ and network access to cdn.prod.website-files.com.
 * Safe to re-run: existing files are skipped.
 * -------------------------------------------------------------- */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CDN = 'https://cdn.prod.website-files.com/';
const sandbox = { window: {} };
vm.createContext(sandbox);
for (const f of ['projects.js', 'afield.js', 'company.js', 'portal-demo.js']) {
  vm.runInContext(readFileSync(join(root, 'data', f), 'utf8'), sandbox, { filename: f });
}

const urls = new Set();
(function walk(v) {
  if (typeof v === 'string') { if (v.startsWith(CDN)) urls.add(v); return; }
  if (v && typeof v === 'object') Object.values(v).forEach(walk);
})(sandbox.window.FGC);

const outDir = join(root, 'assets', 'photography');
mkdirSync(outDir, { recursive: true });
const map = {};
let fetched = 0, skipped = 0, failed = 0;
for (const url of urls) {
  const name = decodeURIComponent(url.split('/').pop()).replace(/[^A-Za-z0-9._-]+/g, '-');
  const rel = `assets/photography/${name}`;
  const abs = join(root, rel);
  if (existsSync(abs)) { map[url] = rel; skipped++; continue; }
  try {
    const res = await fetch(url);
    if (!res.ok) throw new Error(res.status);
    writeFileSync(abs, Buffer.from(await res.arrayBuffer()));
    map[url] = rel; fetched++;
    process.stdout.write(`✓ ${name}\n`);
  } catch (e) { failed++; process.stdout.write(`✗ ${name} (${e.message})\n`); }
}

writeFileSync(join(root, 'data', 'local-photography.js'),
`/* Generated by scripts/localize-photography.mjs on ${new Date().toISOString().slice(0, 10)}.
 * Maps live-site CDN URLs to local copies. Re-run the script to refresh. */
window.FGC = window.FGC || {};
window.FGC.localMap = ${JSON.stringify(map, null, 2)};
`);
console.log(`\n${urls.size} images · ${fetched} downloaded · ${skipped} already local · ${failed} failed`);
