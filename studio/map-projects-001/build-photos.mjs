// Projects map — responsive photography.
// Writes resized copies of every project photograph the map shows into v5/assets/map/ and a manifest,
// v5/record-assets/photos.js. Originals in v5/assets/ stay byte-for-byte and remain the largest source
// in every srcset, so high-density screens still receive the full published file.
// Usage: SHARP=<path to node_modules/sharp> node studio/map-projects-001/build-photos.mjs
import { createRequire } from 'module';
import { createHash } from 'crypto';
import fs from 'fs';
import path from 'path';
const require = createRequire(import.meta.url);
const sharp = require(process.env.SHARP || 'sharp');
const V5 = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../v5');
global.window = {};
new Function(fs.readFileSync(path.join(V5, 'records.js'), 'utf8'))();
const srcs = new Set();
for (const p of window.RECORDS.projects) {
  (p.gallery || []).forEach((g) => srcs.add(g.src));
  if (p.image) srcs.add(p.image);
}
const WIDTHS = [480, 960, 1440];
const out = path.join(V5, 'assets/map');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
const manifest = {};
for (const src of [...srcs].sort()) {
  const file = path.join(V5, src);
  const meta = await sharp(file).metadata();
  const base = path.basename(src, path.extname(src));
  const set = [];
  for (const w of WIDTHS) {
    if (w >= meta.width * 0.9) continue;
    const buf = await sharp(file).resize({ width: w }).jpeg({ quality: 82, progressive: true, mozjpeg: true }).toBuffer();
    const name = `${base}-${w}.${createHash('sha256').update(buf).digest('hex').slice(0, 8)}.jpg`;
    fs.writeFileSync(path.join(out, name), buf);
    set.push([w, '/assets/map/' + name, buf.length]);
  }
  set.push([meta.width, '/' + src, fs.statSync(file).size]);
  manifest[src] = { w: meta.width, h: meta.height, set: set.map(([w, u]) => [w, u]) };
  console.log(src, meta.width + '×' + meta.height, set.map(([w, , b]) => `${w}:${Math.round(b / 1024)}k`).join(' '));
}
fs.writeFileSync(path.join(V5, 'record-assets/photos.js'),
  '/* Generated by studio/map-projects-001/build-photos.mjs; do not edit by hand. Originals are the last entry of each set. */\n' +
  'window.RECORD_PHOTOS=' + JSON.stringify(manifest) + ';\n');
