// /assuranceamerica films — web versions of the videos in the Barnsley Drive folder.
//
// Drive stays the inventory: the page lists the folder's videos live and shows each one that has an
// entry here whose source checksum still matches. A video added to Drive needs this script and a
// deploy; until then it is left out (and logged), never streamed from its multi-hundred-MB original.
//
// For each source <DriveFileId>.mp4 in <sourceDir> (download the originals from Drive under their ids):
//   720p and 1080p H.264/AAC MP4 with fast start (macOS avconvert), and a 1280px JPEG poster frame,
//   written to v5/assets/films/ with content-hashed names (cached immutable), plus lib/films.js.
// Usage: node studio/assuranceamerica-films/build-films.mjs <sourceDir> [posterSeconds=0.5]
import { createHash } from "crypto";
import { execFileSync } from "child_process";
import fs from "fs";
import os from "os";
import path from "path";

const HERE = path.dirname(new URL(import.meta.url).pathname);
const ROOT = path.resolve(HERE, "../..");
const OUT = path.join(ROOT, "v5/assets/films");
const SRC = path.resolve(process.argv[2] || "");
const POSTER_AT = process.argv[3] || "0.5";
const RENDITIONS = [["720", "Preset1280x720"], ["1080", "Preset1920x1080"]];
if (!process.argv[2] || !fs.statSync(SRC).isDirectory()) { console.error("usage: build-films.mjs <sourceDir>"); process.exit(1); }

const hash = (file, algo = "sha256") => createHash(algo).update(fs.readFileSync(file)).digest("hex");
const media = (...a) => JSON.parse(execFileSync("swift", [path.join(HERE, "media.swift"), ...a], { encoding: "utf8" }).trim().split("\n").pop());
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "films-"));
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

const films = {};
for (const name of fs.readdirSync(SRC).filter((f) => /\.(mp4|mov|m4v)$/i.test(f)).sort()) {
  const id = name.replace(/\.[^.]+$/, "");
  const src = path.join(SRC, name);
  const source = media(src);
  const tag = id.slice(0, 8).replace(/[^A-Za-z0-9]/g, "");
  const keep = (file, ext) => {
    const final = `barnsley-${tag}-${path.basename(file, ext).split("-").pop()}.${hash(file).slice(0, 8)}${ext}`;
    fs.copyFileSync(file, path.join(OUT, final));
    return "/assets/films/" + final;
  };
  const entry = { md5: hash(src, "md5"), width: source.width, height: source.height, duration: Math.round(source.duration * 100) / 100, sources: {} };
  const poster = path.join(tmp, `${tag}-poster.jpg`);
  media(src, poster, POSTER_AT, "1280");
  entry.poster = keep(poster, ".jpg");
  for (const [label, preset] of RENDITIONS) {
    const file = path.join(tmp, `${tag}-${label}.mp4`);
    execFileSync("avconvert", ["-s", src, "-p", preset, "-o", file, "--replace", "--multiPass"], { stdio: "ignore" });
    const info = media(file);
    if (info.codec !== "avc1" || !info.audio) throw new Error(`${name} ${label}: unexpected output ${JSON.stringify(info)}`);
    entry.sources[label] = { src: keep(file, ".mp4"), bytes: fs.statSync(file).size };
  }
  films[id] = entry;
  console.log(id, JSON.stringify(entry));
}

fs.writeFileSync(path.join(ROOT, "lib/films.js"),
  "// Generated by studio/assuranceamerica-films/build-films.mjs. Do not edit by hand.\n" +
  "// Drive video id -> web versions. md5 is the Drive original's checksum: if the original changes,\n" +
  "// the film is left out until this file is rebuilt.\n" +
  "export const FILMS = " + JSON.stringify(films, null, 2) + ";\n");
fs.rmSync(tmp, { recursive: true, force: true });
