// Case Study 001 — add photographs to the responsive manifest without touching existing entries.
// (studio/map-projects-001/build-photos.mjs rebuilds every file; this adds only the ones named.)
// Usage: SHARP=<path to node_modules/sharp> node studio/case-study-001/add-photos.mjs assets/projects/a.jpg [...]
import { createRequire } from 'module';
import { createHash } from 'crypto';
import fs from 'fs';
import path from 'path';
const require = createRequire(import.meta.url);
const sharp = require(process.env.SHARP || 'sharp');
const V5 = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../v5');
const file = path.join(V5, 'record-assets/photos.js');
global.window = {};
new Function(fs.readFileSync(file, 'utf8'))();
const manifest = window.RECORD_PHOTOS;
const WIDTHS = [480, 960, 1440, 1920];
for (const src of process.argv.slice(2)) {
  const abs = path.join(V5, src), meta = await sharp(abs).metadata();
  const base = path.basename(src, path.extname(src)), set = [];
  for (const w of WIDTHS) {
    if (w >= meta.width * 0.9) continue;
    const buf = await sharp(abs).resize({ width: w }).jpeg({ quality: 82, progressive: true, mozjpeg: true }).toBuffer();
    const name = `${base}-${w}.${createHash('sha256').update(buf).digest('hex').slice(0, 8)}.jpg`;
    fs.writeFileSync(path.join(V5, 'assets/map', name), buf);
    set.push([w, '/assets/map/' + name, buf.length]);
  }
  set.push([meta.width, '/' + src, fs.statSync(abs).size]);
  manifest[src] = { w: meta.width, h: meta.height, set: set.map(([w, u]) => [w, u]) };
  console.log(src, meta.width + '×' + meta.height, set.map(([w, , b]) => `${w}:${Math.round(b / 1024)}k`).join(' '));
}
fs.writeFileSync(file, '/* Generated by studio/map-projects-001/build-photos.mjs; do not edit by hand. Originals are the last entry of each set. */\n' +
  'window.RECORD_PHOTOS=' + JSON.stringify(manifest) + ';\n');
