import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const file=x=>join(root,x);
const read=x=>readFileSync(file(x),'utf8');
const index=read('v5/studies/the-record-001/index.html');
const app=read('v5/studies/the-record-001/record.js');
const story=read('v5/studies/the-record-001/story-beetlecat.js');
const css=read('v5/studies/the-record-001/story-beetlecat.css');
const ctx={window:{}};
vm.runInNewContext(read('v5/records.js'),ctx);
vm.runInNewContext(read('v5/studies/the-record-001/sites.js'),ctx);
vm.runInNewContext(story,ctx);
const p=ctx.window.RECORDS.projects.find(x=>x.slug==='beetlecat');
assert.ok(p);
assert.equal(p.gallery.length,4);
const it={...p,photos:p.gallery.map(x=>({...x,src:'/'+x.src})),client:p.credits.find(c=>c[0]==='Client')[1],site:ctx.window.RECORD_SITES.sites.beetlecat,year:null};
const html=ctx.window.BEETLECAT_STORY.render(it);
assert.ok(html.includes(p.summary),'published narrative unaltered');
assert.ok(html.includes('Rocket Farm Restaurants'),'client on record');
assert.ok(html.includes('Jared Swafford'),'photography credit');
assert.ok(html.includes('299 N Highland Ave NE'),'public venue location');
assert.ok(html.includes('Not yet verified'),'year not guessed');
assert.ok(html.includes('NOT YET ON FILE'),'missing proof explicit');
assert.equal((html.match(/class="bc-thumb"/g)||[]).length,4);
assert.ok(html.includes('id="r-back"'));
assert.ok(html.includes('id="bc-lightbox"'));
assert.equal(ctx.window.BEETLECAT_STORY.render({...it,slug:'the-optimist'}),null);
for(const frame of it.photos)assert.ok(existsSync(file('v5'+frame.src)),'sourced photo exists: '+frame.src);
for(const name of ['story-beetlecat.css','story-beetlecat.js','record.js'])assert.ok(index.includes(name));
assert.ok(index.indexOf('story-beetlecat.js')<index.indexOf('record.js'),'feature boot order');
assert.ok(app.includes('window.BEETLECAT_STORY.render(it)'));
assert.ok(app.includes('window.BEETLECAT_STORY?.wire(recEl, it)'));
assert.ok(app.includes('delete body.dataset.feature'));
assert.ok(css.includes('@media(max-width:760px)'));
new vm.Script(app);new vm.Script(story);
console.log('Beetlecat 002 integration and provenance checks passed.');
